"""Load real format-1 estimator files written before fitted-state cleanup.

The three archives were produced by public RESPLINTER.save at a3e99ff on
synthetic rows and fixed thresholds, without LightGBM. The adjacent JSON
records that implementation's predictions, guarantees and seeded samples;
neither fixtures nor expected outputs are generated by the code under test.
"""

from bisect import bisect_right
from collections import Counter
from dataclasses import asdict
import hashlib
import json
from pathlib import Path

import numpy as np
import pytest
from sklearn import config_context
from sklearn.base import clone
from sklearn.exceptions import NotFittedError

from splinter import RESPLINTER


DATA = Path(__file__).parent / "data"
REFERENCE = json.loads((DATA / "resplinter_v1_a3e99ff_expected.json").read_text())
MODES = ("full", "recursive", "closure")
OLD_NAMES = ("result_", "candidate_ranking_policy_", "phase1_gap_",
             "phase1_objective_", "phase1_certified_optimal_", "phase1_search_converged_",
             "rashomon_bound_target_", "stepb_mode_", "fill_mode_")


def _reference(mode):
    expected = REFERENCE["models"][mode]
    path = DATA / expected["archive"]
    assert hashlib.sha256(path.read_bytes()).hexdigest() == expected["sha256"]
    with np.load(path, allow_pickle=False) as archive:
        assert int(archive["format_version"]) == 1
        fitted = json.loads(str(archive["fitted_json"]))
        assert "result_" in fitted and "fit_info_" not in fitted
        assert "rashomon_bound_target_" in fitted and "theta_bound_" not in fitted
        return path, expected, fitted, np.array(archive["X"]), np.array(archive["y"])


def _plain_tree(tree):
    # JSON is also the reference manifest's representation of tuples.
    return json.loads(json.dumps(asdict(tree)))


def _tree_sha256(tree):
    content = json.dumps(_plain_tree(tree), sort_keys=True, separators=(",", ":"))
    return hashlib.sha256(content.encode()).hexdigest()


def _variant(path, destination, update):
    with np.load(path, allow_pickle=False) as archive:
        arrays = {name: np.array(archive[name]) for name in archive.files}
    fitted = json.loads(str(arrays["fitted_json"]))
    fitted = update(fitted)
    arrays["fitted_json"] = np.asarray(json.dumps(fitted))
    np.savez(destination, **arrays)
    return destination


def _assert_training_support(tree, X, y):
    leaves = []

    def collect(node):
        if not hasattr(node, "children"):
            leaves.append(node)
        else:
            for child in node.children:
                collect(child)

    collect(tree)
    counts = {id(leaf): Counter() for leaf in leaves}
    for row, label in zip(X, y):
        node = tree
        while hasattr(node, "children"):
            branch = bisect_right(node.thresholds, float(row[node.feature_index]))
            if hasattr(node, "group_map"):
                branch = node.group_map[branch]
            node = node.children[branch]
        counts[id(node)][int(label)] += 1
    for leaf in leaves:
        actual = tuple(counts[id(leaf)][c] for c in range(2))
        assert leaf.n_samples == sum(actual)


def _assert_query_results(model, expected, X, y):
    assert model.tree_count_ == expected["tree_count"]
    assert model.tree_count_at_target_ == expected["tree_count_at_target"]
    assert model.opt_ == expected["opt"]
    np.testing.assert_array_equal(model.classes_, expected["classes"])
    np.testing.assert_array_equal(model.predict(X), expected["predictions"])
    np.testing.assert_array_equal(model.predict_proba(X), expected["probabilities"])
    counts, n_trees, _ = model.predict_class1_counts(X)
    assert counts.tolist() == expected["class1_counts"]
    assert n_trees == expected["class1_count_total"]
    best = model.get_tree(0)
    assert _plain_tree(best) == expected["first_tree"]
    _assert_training_support(best, X, y)
    samples, indices = model.sample_trees(6, seed=17, at_target=True, return_indices=True)
    assert indices == expected["sample_indices"]
    assert [_tree_sha256(tree) for tree in samples] == expected["sample_tree_sha256"]
    for tree in samples:
        _assert_training_support(tree, X, y)
    report = model.guarantee()
    for key in ("search_converged", "best_tree_certified_optimal", "optimality_scope",
                "optimality_gap", "lower_bound", "best_objective", "search_objective",
                "theta", "objective_bound", "inclusion_exact", "coverage_scope",
                "complete", "count_saturated"):
        assert report[key] == expected["guarantee"][key], key


@pytest.mark.parametrize("mode", MODES)
def test_precleanup_format1_load_preserves_the_fitted_set_and_metadata(mode):
    path, expected, old, X, y = _reference(mode)
    model = RESPLINTER.load(path)
    _assert_query_results(model, expected, X, y)
    assert model.classes_.dtype.str == old["classes_"]["dtype"]
    assert model.atom_mode is False
    assert model.binary_threshold_backfill is True
    assert model.theta_bound_ == old["rashomon_bound_target_"]
    assert model.fit_info_["raw_result"] == old["result_"]
    assert model.fit_info_["candidate_ranking_policy"] == old["candidate_ranking_policy_"]
    assert model.fit_info_["fill_mode"] == mode
    assert model.fit_info_["solve_depth"] == old["solve_depth_"]
    assert model.fit_info_["remaining_depth"] == old["remaining_depth_"]
    assert model.fit_info_["incomplete_reason_codes"] == expected["incomplete_reason_codes"]
    assert model.fit_info_["completion"]["mode"] == (
        "recursive" if expected["stepb_mode"] == "paper" else "none")
    assert isinstance(model.rashomon_incomplete_reason_, list)
    if mode == "closure":
        # Old closure files said fill_mode_=recursive despite using greedy
        # completion. The new user-facing label must state what ran.
        assert old["fill_mode_"] == "recursive"
        assert not model.rashomon_complete_
        assert any("greedily" in reason for reason in model.rashomon_incomplete_reason_)
    else:
        assert model.rashomon_complete_
        assert model.rashomon_incomplete_reason_ == []
    if mode == "full":
        # None meant full depth at a3e99ff; recomputing with the new None
        # default would incorrectly describe this as a recursive fit.
        assert old["solve_depth_"] == model.max_depth
        assert old["remaining_depth_"] == 0
        assert model.lookahead_depth == model.max_depth
    first = model.fit_info_["first_stage"]
    for name, value in expected["first_stage"].items():
        assert first["lower_bound" if name == "lowerbound" else name] == value, name
    assert not any(hasattr(model, name) for name in OLD_NAMES)


@pytest.mark.parametrize("mode", MODES)
def test_migrated_format1_model_resaves_with_current_fitted_names(mode, tmp_path):
    path, expected, _, X, y = _reference(mode)
    migrated = RESPLINTER.load(path)
    current = tmp_path / f"{mode}.npz"
    migrated.save(current)
    with np.load(current, allow_pickle=False) as archive:
        fitted = json.loads(str(archive["fitted_json"]))
        assert "fit_info_" in fitted and "theta_bound_" in fitted
        assert not any(name in fitted for name in OLD_NAMES)
    restored = RESPLINTER.load(current)
    _assert_query_results(restored, expected, X, y)
    assert restored.atom_mode is False
    assert restored.binary_threshold_backfill is True
    if mode == "full":
        assert restored.lookahead_depth == restored.max_depth
    assert restored.guarantee() == migrated.guarantee()
    assert restored.fit_info_ == migrated.fit_info_


@pytest.mark.parametrize("mode", MODES)
def test_migrated_model_clone_preserves_settings_without_copying_fitted_state(mode):
    path, expected, _, X, y = _reference(mode)
    migrated = RESPLINTER.load(path)
    unfitted = clone(migrated)
    assert type(unfitted) is type(migrated)
    assert unfitted.get_params() == migrated.get_params()
    assert unfitted.fixed_thresholds == migrated.fixed_thresholds
    assert unfitted.fixed_thresholds is not migrated.fixed_thresholds
    assert unfitted.atom_mode is False
    assert unfitted.binary_threshold_backfill is True
    assert unfitted.lookahead_depth == migrated.lookahead_depth
    for name in ("dag_", "fit_info_", "classes_", "_train_X", "_train_y",
                 "_fit_thresholds", "_n_classes"):
        assert not hasattr(unfitted, name), name
    with pytest.raises(NotFittedError):
        unfitted.predict(X)
    original_labels = migrated.classes_[y]
    unfitted.fit(X, original_labels, feature_names=migrated.feature_names_)
    _assert_query_results(unfitted, expected, X, y)


def test_migrated_model_clone_preserves_sklearn_metadata_requests():
    path, _, _, _, _ = _reference("full")
    with config_context(enable_metadata_routing=True):
        model = RESPLINTER.load(path).set_fit_request(feature_names=True)
        unfitted = clone(model)
        assert unfitted.get_metadata_routing().fit.requests == {"feature_names": True}
    assert unfitted.atom_mode is False
    assert unfitted.binary_threshold_backfill is True
    assert not hasattr(unfitted, "dag_")


def test_old_report_without_ranking_policy_loads_without_inventing_a_policy(tmp_path):
    path, expected, _, X, y = _reference("full")

    def without_policy(fitted):
        fitted.pop("candidate_ranking_policy_", None)
        fitted["result_"].pop("candidate_ranking_policy", None)
        return fitted

    variant = _variant(path, tmp_path / "no_policy.npz", without_policy)
    model = RESPLINTER.load(variant)
    assert model.fit_info_["candidate_ranking_policy"] is None
    _assert_query_results(model, expected, X, y)


def test_old_nominal_optimal_flag_is_not_promoted_to_a_certificate(tmp_path):
    path, _, _, _, _ = _reference("full")

    def without_certificate(fitted):
        fitted.pop("phase1_certified_optimal_", None)
        result = fitted["result_"]
        result.pop("phase1_certified_optimal", None)
        result["phase1_is_optimal"] = True
        result["phase1_gap"] = 0.0
        result["phase1_lowerbound"] = result["phase1_objective"]
        return fitted

    variant = _variant(path, tmp_path / "no_certificate.npz", without_certificate)
    model = RESPLINTER.load(variant)
    assert model.fit_info_["first_stage"]["is_optimal"] is True
    report = model.guarantee()
    assert not report["best_tree_certified_optimal"]
    assert report["optimality_gap"] is None
    assert report["lower_bound"] is None


@pytest.mark.parametrize("corruption", ["missing_result", "invalid_result", "invalid_fitted"])
def test_corrupt_precleanup_metadata_raises_value_error(corruption, tmp_path):
    path, _, _, _, _ = _reference("full")

    def corrupt_metadata(fitted):
        if corruption == "missing_result":
            del fitted["result_"]
        elif corruption == "invalid_result":
            fitted["result_"] = []
        else:
            fitted = []
        return fitted

    corrupt = _variant(path, tmp_path / "corrupt.npz", corrupt_metadata)
    with pytest.raises(ValueError, match="valid saved RESPLINTER"):
        RESPLINTER.load(corrupt)
